/// Builds the two subtitle files of the AI pipeline: a bilingual ASS placed
/// next to the video (Chinese on top with a larger font, the original line
/// below it) and a Chinese-only SRT for players that ignore styles.
///
/// Both builders are pure: the caller passes transcript segments and the
/// id -> Chinese translation map, so the layout is unit-testable without files.
library;

import 'transcript.dart';

const int kAssPlayResX = 1920;
const int kAssPlayResY = 1080;

/// Style names used by [buildBilingualAss]. The Chinese style is emitted first
/// for every segment so libass stacks it above the original line.
const String kChineseStyle = 'ZH';
const String kOriginalStyle = 'EN';

/// `H:MM:SS.cc` as required by ASS timestamps. Hours are not zero padded;
/// characters below one centisecond are truncated.
String formatAssTime(Duration value) {
  final safe = value.isNegative ? Duration.zero : value;
  final hours = safe.inHours;
  final minutes = safe.inMinutes.remainder(60);
  final seconds = safe.inSeconds.remainder(60);
  final centis = safe.inMilliseconds.remainder(1000) ~/ 10;
  return '$hours:${_two(minutes)}:${_two(seconds)}.${_two(centis)}';
}

/// `HH:MM:SS,mmm`, the SRT timestamp format.
String formatSrtTime(Duration value) {
  final safe = value.isNegative ? Duration.zero : value;
  final hours = safe.inHours;
  final minutes = safe.inMinutes.remainder(60);
  final seconds = safe.inSeconds.remainder(60);
  final millis = safe.inMilliseconds.remainder(1000);
  return '${_two(hours)}:${_two(minutes)}:${_two(seconds)},${_three(millis)}';
}

/// Escapes text so it survives libass parsing.
///
/// `\` becomes `\\`, `{`/`}` become `\{`/`\}` (otherwise they would open an
/// override block), and line breaks become `\N`. Commas are left as-is: the
/// ASS `Dialogue` text is the last field of the line, so a comma inside it can
/// never be mistaken for a field separator.
String escapeAssText(String text) {
  final normalized = text.replaceAll('\r\n', '\n').replaceAll('\r', '\n');
  return normalized
      .replaceAll('\\', '\\\\')
      .replaceAll('{', '\\{')
      .replaceAll('}', '\\}')
      .replaceAll('\n', '\\N');
}

/// Escapes text for an SRT block. SRT has no escape syntax, so only line
/// breaks are normalized; blank lines are removed because an empty line ends
/// the block.
String escapeSrtText(String text) {
  final normalized = text.replaceAll('\r\n', '\n').replaceAll('\r', '\n');
  final lines = normalized
      .split('\n')
      .map((line) => line.trimRight())
      .where((line) => line.trim().isNotEmpty);
  return lines.join('\n').trim();
}

/// Builds a complete bilingual ASS document.
///
/// Each segment produces two `Dialogue` lines with the same timing: the
/// Chinese style first (larger font, higher margin) and the original style
/// second (smaller font, closer to the bottom edge).
String buildBilingualAss({
  required List<TranscriptSegment> segments,
  required Map<int, String> translations,
  String title = 'Praxino AI subtitles',
}) {
  final buffer = StringBuffer()
    ..writeln('[Script Info]')
    ..writeln('; Generated by Praxino: local Whisper transcript + AI translation')
    ..writeln('Title: ${_singleLine(title)}')
    ..writeln('ScriptType: v4.00+')
    ..writeln('WrapStyle: 0')
    ..writeln('ScaledBorderAndShadow: yes')
    ..writeln('YCbCr Matrix: TV.709')
    ..writeln('PlayResX: $kAssPlayResX')
    ..writeln('PlayResY: $kAssPlayResY')
    ..writeln()
    ..writeln('[V4+ Styles]')
    ..writeln('Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, '
        'OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, '
        'ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, '
        'Alignment, MarginL, MarginR, MarginV, Encoding')
    ..writeln('Style: $kChineseStyle,Microsoft YaHei,64,&H00FFFFFF,'
        '&H000000FF,&H00000000,&H7F000000,0,0,0,0,100,100,0,0,1,3,1,2,60,60,150,1')
    ..writeln('Style: $kOriginalStyle,Arial,40,&H00E6E6E6,'
        '&H000000FF,&H00000000,&H7F000000,0,0,0,0,100,100,0,0,1,2,1,2,60,60,70,1')
    ..writeln()
    ..writeln('[Events]')
    ..writeln('Format: Layer, Start, End, Style, Name, MarginL, MarginR, '
        'MarginV, Effect, Text');

  for (final segment in segments) {
    final start = formatAssTime(segment.start);
    final end = formatAssTime(_safeEnd(segment));
    final chinese = escapeAssText(_chineseText(segment, translations));
    final original = escapeAssText(segment.text);
    buffer
      ..writeln('Dialogue: 0,$start,$end,$kChineseStyle,,0,0,0,,$chinese')
      ..writeln('Dialogue: 0,$start,$end,$kOriginalStyle,,0,0,0,,$original');
  }
  return buffer.toString();
}

/// Builds a Chinese-only SRT document (the original text is used when a
/// segment has no translation, so the output never loses a line).
String buildChineseSrt({
  required List<TranscriptSegment> segments,
  required Map<int, String> translations,
}) {
  final buffer = StringBuffer();
  for (var index = 0; index < segments.length; index++) {
    final segment = segments[index];
    final text = escapeSrtText(_chineseText(segment, translations));
    if (text.isEmpty) continue;
    buffer
      ..writeln(index + 1)
      ..writeln('${formatSrtTime(segment.start)} --> '
          '${formatSrtTime(_safeEnd(segment))}')
      ..writeln(text)
      ..writeln();
  }
  return buffer.toString();
}

String _chineseText(
  TranscriptSegment segment,
  Map<int, String> translations,
) {
  final value = translations[segment.id];
  if (value == null) return segment.text;
  final trimmed = value.trim();
  return trimmed.isEmpty ? segment.text : trimmed;
}

/// Zero-length segments would make libass drop the line; give them 500 ms.
Duration _safeEnd(TranscriptSegment segment) {
  if (segment.end > segment.start) return segment.end;
  return segment.start + const Duration(milliseconds: 500);
}

String _singleLine(String value) =>
    value.replaceAll(RegExp(r'[\r\n]+'), ' ').trim();

String _two(int value) => value.toString().padLeft(2, '0');

String _three(int value) => value.toString().padLeft(3, '0');
